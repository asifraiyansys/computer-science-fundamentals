#include <bits/stdc++.h>

using namespace std;

int main()
{
    int a = 20, b = 35;

    // min() function
    cout << min(a, b) << endl;
    cout << min({10, 4, 50}) << endl;

    // max() function
    cout << max(a, b) << endl;
    cout << max({10, 50, 30, 20}) << endl;

    // swape() function
    swap(a, b);
    cout << a << " " << b << endl;

    return 0;
}